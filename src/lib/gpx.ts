// Build-time loading of the GPS routes in the mountaineering posts. A post's `route` is one
// .gpx file in public/ or a list of them (a route recorded in several parts), which are stitched
// into one before the analysis in gpx-core.ts.

import { readFileSync } from "node:fs";
import path from "node:path";
import { analyzeTrack, parseGpx, stitchTracks, type GpxTrack, type RouteData, type Waypoint } from "./gpx-core";
import type { WaypointKind } from "./waypoint-kinds";

export type { RouteData, RoutePoint } from "./gpx-core";

/** Frontmatter `route`: public path(s) of .gpx files, e.g. "/assets/lib/union.gpx" */
export type RouteFiles = string | string[];

const trackCache = new Map<string, GpxTrack>();
const routeCache = new Map<string, RouteData>();

export const routeFileList = (files: RouteFiles) => (Array.isArray(files) ? files : [files]);

/** The route's files joined into one track. */
export function loadTrack(files: RouteFiles): GpxTrack {
  const list = routeFileList(files);
  const key = list.join("\n");
  let track = trackCache.get(key);
  if (!track) {
    track = stitchTracks(list.map(readTrack));
    trackCache.set(key, track);
  }
  return track;
}

/** Load and analyze a route for the RouteMap component. */
export function loadRoute(files: RouteFiles): RouteData {
  const key = routeFileList(files).join("\n");
  let data = routeCache.get(key);
  if (!data) {
    data = analyzeTrack(loadTrack(files));
    routeCache.set(key, data);
  }
  return data;
}

/** Frontmatter `waypoints`: points marked in the post, besides the file's own */
export interface PostWaypoint {
  name: string;
  lat: number;
  lon: number;
  kind: WaypointKind;
  ele?: number;
  note?: string;
}

export function postWaypoints(extra: PostWaypoint[] = []): Waypoint[] {
  return extra.map(({ note, ...w }) => ({ ...w, desc: note }));
}

/** The route with the post's own marked points added to the file's. */
export function withPostWaypoints<T extends { waypoints: Waypoint[] }>(route: T, extra: PostWaypoint[] = []): T {
  return extra.length ? { ...route, waypoints: [...route.waypoints, ...postWaypoints(extra)] } : route;
}

/** Whether the download is generated (stitched files, or points added in the post) rather than the file itself */
export const generatedDownload = (files: RouteFiles, extra: PostWaypoint[] = []) => routeFileList(files).length > 1 || extra.length > 0;

/**
 * URL of the GPX file to download: the file itself, or the version generated by
 * src/pages/routes/[slug].gpx.ts for a route in several parts or with points marked in the post.
 */
export function routeDownloadPath(files: RouteFiles, slug: string, extra: PostWaypoint[] = []) {
  return generatedDownload(files, extra) ? `/routes/${slug}.gpx` : routeFileList(files)[0];
}

function readTrack(publicPath: string): GpxTrack {
  const file = path.join(process.cwd(), "public", publicPath.replace(/^\/+/, ""));
  let xml: string;
  try {
    xml = readFileSync(file, "utf8");
  } catch {
    throw new Error(`Route file not found: "${publicPath}" (expected at ${file})`);
  }
  const track = parseGpx(xml);
  if (track.points.length === 0) throw new Error(`Route file has no track points: "${publicPath}"`);
  return track;
}
